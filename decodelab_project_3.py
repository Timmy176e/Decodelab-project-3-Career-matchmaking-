# Step 1 (updated): Expanded career path dataset
career_paths = {
    "Data Scientist": "Python SQL Machine Learning Data Analysis Statistics Pandas",
    "DevOps Engineer": "AWS Docker Kubernetes CI/CD Linux Git",
    "Backend Developer": "Java Python SQL APIs REST Git",
    "Cloud Engineer": "AWS Azure Google Cloud Terraform Docker Kubernetes Networking",
    "Sys Admin": "Linux Windows Server Networking Bash Scripting Security Backup",
    "Frontend Developer": "JavaScript React HTML CSS TypeScript Git UI",
    "Data Analyst": "SQL Excel Data Analysis Visualization Tableau Statistics Python"
}

career_names = list(career_paths.keys())
career_docs = list(career_paths.values())

print(career_names)
print(career_docs)

# Step 2: Fit TF-IDF on our career path documents
vectorizer = TfidfVectorizer()
career_vectors = vectorizer.fit_transform(career_docs)

print(vectorizer.get_feature_names_out())
print(career_vectors.shape)
print(career_vectors.toarray())

# Step 3: Take a user's skills and vectorize with the SAME vectorizer
user_skills = input("Enter your skills (comma or space separated): ")

# .transform, NOT .fit_transform — this reuses the vocabulary TF-IDF
# already learned from career_docs in Step 2. That's the "exact same
# vocabulary" rule: fit_transform here would relearn a new vocabulary
# from just the user's words and break the comparison.
user_vector = vectorizer.transform([user_skills])

print(user_vector.toarray())

# Step 4: Score the user vector against every career vector
similarity_scores = cosine_similarity(user_vector, career_vectors)

print(similarity_scores)

# Step 5: Pair scores with names, rank them, show Top-N
scores = similarity_scores[0]  # pull the single row out

ranked = list(zip(career_names, scores))      # [(name, score), ...]
ranked.sort(key=lambda pair: pair[1], reverse=True)  # highest first

top_n = 3
print(f"Top {top_n} career path matches:")
for name, score in ranked[:top_n]:
    print(f"{name}: {score:.2f}")

# Step 6: Package the recommendation logic into one function
def recommend_career(skills_input, top_n=3):
    user_vector = vectorizer.transform([skills_input])
    scores = cosine_similarity(user_vector, career_vectors)[0]
    ranked = list(zip(career_names, scores))
    ranked.sort(key=lambda pair: pair[1], reverse=True)
    return ranked[:top_n]

# Try it with a different skill set
results = recommend_career("Docker Kubernetes AWS Networking")
for name, score in results:
    print(f"{name}: {score:.2f}")